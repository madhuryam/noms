// Helper to get items for a specific location
export function getItemsForLocation(location: string): LocationItems {
  switch (location) {
    case 'pantry':
      return pantryItems;
    case 'fridge':
      return fridgeItems;
    case 'freezer':
      return freezerItems;
    case 'spices':
      return spicesItems;
    case 'sauces':
      return saucesItems;
    case 'snacks':
      return snacksItems;
    default:
      return { categories: [] };
  }
}
